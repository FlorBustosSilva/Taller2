    public static double getEfectividad(String tipoAtacante, String tipoDefensor) {
        int fila = getIndiceTipo(tipoAtacante);
        int col  = getIndiceTipo(tipoDefensor);
        if (fila == -1 || col == -1) return 1.0;
        return EFECTIVIDAD[fila][col];
    }

    private static int getIndiceTipo(String tipo) {
        String tipoNorm = tipo.trim();
        for (int i = 0; i < TIPOS.length; i++) {
            if (TIPOS[i].equalsIgnoreCase(tipoNorm)) return i;
        }
        return -1;
    }
